#!/usr/bin/env python3
"""Writes docs/CALL-GRAPH.md: who calls whom, worked out from the source (a class "calls" another when its code names it).

Run from the repository root:  python3 scripts/callgraph.py
The diagram groups controllers by screen area so it stays readable; services and DAOs are shown one by one.
"""
import collections
import os
import re

ROOT = os.path.join("src", "main", "java", "com", "aniplato")
OUT = os.path.join("docs", "CALL-GRAPH.md")


def classes():
    found = {}
    for folder, _, names in os.walk(ROOT):
        for name in names:
            if name.endswith(".java"):
                path = os.path.join(folder, name)
                found[name[:-5]] = os.path.relpath(path, ROOT).replace(os.sep, "/")
    return found


def body(path):
    text = open(os.path.join(ROOT, path)).read()
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)   # a name in a comment is not a call
    text = re.sub(r"//[^\n]*", "", text)
    return re.sub(r"^import .*$", "", text, flags=re.M)


def area(path):
    """The screen area a controller belongs to."""
    if path.startswith("controller/admin/"):
        return "Admin"
    if path.startswith("controller/donor/"):
        return "Donor"
    if path.startswith("controller/foodgroup/"):
        return "FoodGroup"
    if path.endswith("DialogController.java") or path.endswith("DialogSpec.java"):
        return "Dialogs"
    if path.startswith("controller/shared/"):
        return "Shared"
    if re.search(r"/(Login|Register|RegisterStep2|RegisterSubmitted)Controller", "/" + path[len("controller/"):]):
        return "Entry"
    return "Frame"   # shell, profile and the helpers every screen uses


AREAS = {
    "Entry": "Login and Register",
    "Frame": "Shell, Profile, helpers",
    "Admin": "Admin screens",
    "Donor": "Donor screens",
    "FoodGroup": "Food group screens",
    "Shared": "Shared screens",
    "Dialogs": "Dialogs",
}


def main():
    by_name = classes()
    kind = lambda p: p.split("/")[0]
    code = {n: body(p) for n, p in by_name.items()}
    uses = collections.defaultdict(set)
    for name, path in by_name.items():
        for other, other_path in by_name.items():
            if other != name and re.search(r"\b" + other + r"\b", code[name]):
                uses[name].add(other)

    service = sorted(n for n, p in by_name.items() if kind(p) == "service" and n != "DetailRules")
    dao = sorted(n for n, p in by_name.items() if kind(p) == "dao")
    controllers = [n for n, p in by_name.items() if kind(p) == "controller"]

    area_to_service = collections.defaultdict(set)
    for c in controllers:
        for s in uses[c] & set(service):
            area_to_service[area(by_name[c])].add(s)
    service_edges = sorted((s, t) for s in service for t in uses[s] & set(service))
    service_dao = sorted((s, d) for s in service for d in uses[s] & set(dao))

    lines = ["flowchart LR"]
    lines.append('  subgraph V["Controllers (one per screen)"]')
    for key, label in AREAS.items():
        lines.append(f'    {key}["{label}"]')
    lines.append("  end")
    lines.append('  subgraph S["Services (the rules, one transaction per action)"]')
    lines += [f"    {s}" for s in service]
    lines.append("  end")
    lines.append(f'  D[("DAOs: SQL only, one per table ({len(dao)})  →  MySQL")]')
    for key in AREAS:
        for s in sorted(area_to_service[key]):
            lines.append(f"  {key} --> {s}")
    for s, t in service_edges:
        lines.append(f"  {s} -.-> {t}")
    lines.append("  S ==> D")
    graph = "\n".join(lines)

    def size(folder):
        paths = [p for p in by_name.values() if kind(p) == folder]
        return len(paths), sum(len(open(os.path.join(ROOT, p)).readlines()) for p in paths)

    daos = "\n".join("| %s | %s |" % (s, ", ".join(d for _, d in service_dao if _ == s) or "none") for s in service)
    rows = "\n".join("| %s | %d | %d |" % ((f,) + size(f)) for f in ["controller", "service", "dao", "model", "util"])
    fxml = [os.path.join(d, n) for d, _, ns in os.walk(os.path.join(ROOT, "view")) for n in ns if n.endswith(".fxml")]

    text = f"""# Call graph

Generated by `python3 scripts/callgraph.py` from the source, so it shows what the code does, not what was planned.
A solid arrow is "calls"; a dotted arrow is one service using another; the thick arrow is every service reaching its DAOs (table below). Nothing points up: no DAO calls a service, no
service calls a controller, and no controller calls a DAO (`ArchitectureTest` fails the build if one does).

```mermaid
{graph}
```

## Size

| Layer | Files | Lines |
|---|---|---|
{rows}
| view (FXML) | {len(fxml)} | {sum(len(open(f).readlines()) for f in fxml)} |

## Which DAOs each service uses

| Service | DAOs |
|---|---|
{daos}

## Reading it

- A controller area reaches a service by name only; it never sees SQL. The edges from Dialogs are the popups' buttons.
- `MaintenanceService` is the one service that only calls other services (A4).
- A service-to-service arrow means the second one owns the rule: `SafetyService` suspends through `RegistrationService`,
  `ReportService` raises its overdue flag through `SafetyService`, and `OfferService` and `PostService` share status changes.
"""
    with open(OUT, "w") as handle:
        handle.write(text)
    print("wrote", OUT, "-", len(service), "services,", len(dao), "daos,", len(controllers), "controllers")


if __name__ == "__main__":
    main()
